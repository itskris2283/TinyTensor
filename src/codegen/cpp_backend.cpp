CppBackend::CppBackend(CompileOptions options)
    : options_(std::move(options)) {
    if (options_.target_isa == TargetISA::AVX2_FMA) {
        if (!simd::has_avx2()) {
            options_.target_isa = TargetISA::Scalar;
            options_.enable_fma = false;
        } else if (!simd::has_fma3()) {
            options_.target_isa = TargetISA::AVX2;
            options_.enable_fma = false;
        }
    } else if (options_.target_isa == TargetISA::AVX2) {
        if (!simd::has_avx2()) {
            options_.target_isa = TargetISA::Scalar;
            options_.enable_fma = false;
        } else if (options_.enable_fma && !simd::has_fma3()) {
            options_.enable_fma = false;
        }
    } else {
        options_.enable_fma = false;
    }
}

std::string CppBackend::generate_code(const Graph& graph) const {
    std::ostringstream ss;
    ss << "// Generated by TinyTensor C++ Backend v0.1.1\n";
    ss << "#include <cmath>\n";
    ss << "#include <cstring>\n";
    ss << "#include <cstdint>\n";
    ss << "#include <algorithm>\n";
    bool is_avx = (options_.target_isa == TargetISA::AVX2 || options_.target_isa == TargetISA::AVX2_FMA);
    if (is_avx) {
        ss << "#include <immintrin.h>\n";
    }
    ss << "\nextern \"C\" {\n\n";

    ss << "int tinytensor_kernel_entry(void** input_ptrs, void** output_ptrs, void** temp_ptrs) {\n";
    ss << "    (void)temp_ptrs;\n";

    // Bind inputs
    for (size_t i = 0; i < graph.inputs().size(); ++i) {
        Node* in_node = graph.inputs()[i];
        std::string type_str = (in_node->dtype() == DType::Float32) ? "float" : "double";
        ss << "    const " << type_str << "* node_" << in_node->id()
           << " = static_cast<const " << type_str << "*>(input_ptrs[" << i << "]);\n";
    }

    // Allocate local or output variables for each node
    std::vector<Node*> topo = graph.topological_sort();
    std::unordered_map<const Node*, size_t> output_index;
    for (size_t i = 0; i < graph.outputs().size(); ++i) {
        output_index[graph.outputs()[i]] = i;
    }

    for (Node* node : topo) {
        if (node->is_input()) continue;

        std::string type_str = (node->dtype() == DType::Float32) ? "float" : "double";
        int64_t numel = node->shape().numel();

        if (output_index.count(node)) {
            // Node is a graph output: directly target output buffer
            size_t out_idx = output_index[node];
            ss << "    " << type_str << "* node_" << node->id()
               << " = static_cast<" << type_str << "*>(output_ptrs[" << out_idx << "]);\n";
        } else {
            // Allocate heap buffer for intermediate result
            ss << "    " << type_str << "* node_" << node->id()
               << " = new " << type_str << "[" << numel << "];\n";
        }

        // Emit computation
        switch (node->op_type()) {
            case OpType::Constant: {
                const Tensor& cv = node->constant_value();
                ss << "    {\n";
                ss << "        static const " << type_str << " c_data[] = {";
                for (int64_t i = 0; i < numel; ++i) {
                    if (node->dtype() == DType::Float32) {
                        ss << "float(" << cv.data<float>()[i] << ")";
                    } else {
                        ss << "double(" << cv.data<double>()[i] << ")";
                    }
                    if (i + 1 < numel) ss << ", ";
                }
                ss << "};\n";
                ss << "        std::memcpy(node_" << node->id() << ", c_data, " << numel << " * sizeof(" << type_str << "));\n";
                ss << "    }\n";
                break;
            }

            case OpType::Add:
            case OpType::Sub:
            case OpType::Mul:
            case OpType::Div: {
                Node* a = node->inputs()[0];
                Node* b = node->inputs()[1];
                std::string op_sym = (node->op_type() == OpType::Add) ? "+" :
                                     (node->op_type() == OpType::Sub) ? "-" :
                                     (node->op_type() == OpType::Mul) ? "*" : "/";

                if (a->shape() == b->shape() && options_.target_isa == TargetISA::AVX2 &&
                    node->dtype() == DType::Float32 && numel >= 8) {
                    // Vectorized AVX2 contiguous path
                    std::string avx_intr = (node->op_type() == OpType::Add) ? "_mm256_add_ps" :
                                           (node->op_type() == OpType::Sub) ? "_mm256_sub_ps" :
                                           (node->op_type() == OpType::Mul) ? "_mm256_mul_ps" : "_mm256_div_ps";
                    ss << "    {\n";
                    ss << "        int64_t i = 0;\n";
                    ss << "        int64_t limit = " << numel << " - 7;\n";
                    ss << "        for (; i < limit; i += 8) {\n";
                    ss << "            __m256 va = _mm256_loadu_ps(node_" << a->id() << " + i);\n";
                    ss << "            __m256 vb = _mm256_loadu_ps(node_" << b->id() << " + i);\n";
                    ss << "            __m256 vr = " << avx_intr << "(va, vb);\n";
                    ss << "            _mm256_storeu_ps(node_" << node->id() << " + i, vr);\n";
                    ss << "        }\n";
                    ss << "        for (; i < " << numel << "; ++i) {\n";
                    ss << "            node_" << node->id() << "[i] = node_" << a->id() << "[i] " << op_sym << " node_" << b->id() << "[i];\n";
                    ss << "        }\n";
                    ss << "    }\n";
                } else if (a->shape() == b->shape()) {
                    // Contiguous scalar path
                    ss << "    for (int64_t i = 0; i < " << numel << "; ++i) {\n";
                    ss << "        node_" << node->id() << "[i] = node_" << a->id() << "[i] " << op_sym << " node_" << b->id() << "[i];\n";
                    ss << "    }\n";
                } else {
                    // General stride-zero broadcasted path
                    int64_t tgt_rank = static_cast<int64_t>(node->shape().ndim());
                    if (tgt_rank == 0 || numel == 1) {
                        ss << "    node_" << node->id() << "[0] = node_" << a->id() << "[0] " << op_sym << " node_" << b->id() << "[0];\n";
                    } else {
                        // Compute broadcast strides for a and b
                        int64_t a_rank = static_cast<int64_t>(a->shape().ndim());
                        int64_t b_rank = static_cast<int64_t>(b->shape().ndim());
                        Strides a_contig = Strides::compute_contiguous(a->shape());
                        Strides b_contig = Strides::compute_contiguous(b->shape());

                        std::vector<int64_t> a_bcast(static_cast<size_t>(tgt_rank), 0);
                        std::vector<int64_t> b_bcast(static_cast<size_t>(tgt_rank), 0);

                        int64_t a_diff = tgt_rank - a_rank;
                        for (int64_t i = 0; i < tgt_rank; ++i) {
                            if (i >= a_diff) {
                                size_t src_i = static_cast<size_t>(i - a_diff);
                                if (a->shape()[src_i] == node->shape()[static_cast<size_t>(i)]) {
                                    a_bcast[static_cast<size_t>(i)] = a_contig[src_i];
                                }
                            }
                        }

                        int64_t b_diff = tgt_rank - b_rank;
                        for (int64_t i = 0; i < tgt_rank; ++i) {
                            if (i >= b_diff) {
                                size_t src_i = static_cast<size_t>(i - b_diff);
                                if (b->shape()[src_i] == node->shape()[static_cast<size_t>(i)]) {
                                    b_bcast[static_cast<size_t>(i)] = b_contig[src_i];
                                }
                            }
                        }

                        // Emit nested loops for each dimension in target shape
                        for (int64_t d = 0; d < tgt_rank; ++d) {
                            ss << std::string(static_cast<size_t>(4 + d * 4), ' ')
                               << "for (int64_t i" << d << " = 0; i" << d << " < "
                               << node->shape()[static_cast<size_t>(d)] << "; ++i" << d << ") {\n";
                        }

                        std::string indent(static_cast<size_t>(4 + tgt_rank * 4), ' ');
                        ss << indent << "int64_t idx_a = ";
                        bool first_a = true;
                        for (int64_t d = 0; d < tgt_rank; ++d) {
                            if (a_bcast[static_cast<size_t>(d)] > 0) {
                                if (!first_a) ss << " + ";
                                ss << "i" << d << " * " << a_bcast[static_cast<size_t>(d)];
                                first_a = false;
                            }
                        }
                        if (first_a) ss << "0";
                        ss << ";\n";

                        ss << indent << "int64_t idx_b = ";
                        bool first_b = true;
                        for (int64_t d = 0; d < tgt_rank; ++d) {
                            if (b_bcast[static_cast<size_t>(d)] > 0) {
                                if (!first_b) ss << " + ";
                                ss << "i" << d << " * " << b_bcast[static_cast<size_t>(d)];
                                first_b = false;
                            }
                        }
                        if (first_b) ss << "0";
                        ss << ";\n";

                        Strides out_contig = Strides::compute_contiguous(node->shape());
                        ss << indent << "int64_t idx_out = ";
                        for (int64_t d = 0; d < tgt_rank; ++d) {
                            if (d > 0) ss << " + ";
                            ss << "i" << d << " * " << out_contig[static_cast<size_t>(d)];
                        }
                        ss << ";\n";

                        ss << indent << "node_" << node->id() << "[idx_out] = node_"
                           << a->id() << "[idx_a] " << op_sym << " node_" << b->id() << "[idx_b];\n";

                        for (int64_t d = tgt_rank - 1; d >= 0; --d) {
                            ss << std::string(static_cast<size_t>(4 + d * 4), ' ') << "}\n";
                        }
                    }
                }
                break;
            }

            case OpType::ReLU: {
                Node* a = node->inputs()[0];
                if (is_avx && node->dtype() == DType::Float32 && numel >= 8) {
                    ss << "    {\n";
                    ss << "        int64_t i = 0;\n";
                    ss << "        int64_t limit = " << numel << " - 7;\n";
                    ss << "        __m256 zero = _mm256_setzero_ps();\n";
                    ss << "        for (; i < limit; i += 8) {\n";
                    ss << "            __m256 va = _mm256_loadu_ps(node_" << a->id() << " + i);\n";
                    ss << "            __m256 vr = _mm256_max_ps(va, zero);\n";
                    ss << "            _mm256_storeu_ps(node_" << node->id() << " + i, vr);\n";
                    ss << "        }\n";
                    ss << "        for (; i < " << numel << "; ++i) {\n";
                    ss << "            node_" << node->id() << "[i] = (node_" << a->id() << "[i] > 0.0f) ? node_" << a->id() << "[i] : 0.0f;\n";
                    ss << "        }\n";
                    ss << "    }\n";
                } else {
                    ss << "    for (int64_t i = 0; i < " << numel << "; ++i) {\n";
                    ss << "        node_" << node->id() << "[i] = (node_" << a->id() << "[i] > 0) ? node_" << a->id() << "[i] : 0;\n";
                    ss << "    }\n";
                }
                break;
            }

            case OpType::Sigmoid: {
                Node* a = node->inputs()[0];
                ss << "    for (int64_t i = 0; i < " << numel << "; ++i) {\n";
                ss << "        " << type_str << " x = node_" << a->id() << "[i];\n";
                ss << "        if (x >= 0) {\n";
                ss << "            node_" << node->id() << "[i] = 1 / (1 + std::exp(-x));\n";
                ss << "        } else {\n";
                ss << "            " << type_str << " ex = std::exp(x);\n";
                ss << "            node_" << node->id() << "[i] = ex / (1 + ex);\n";
                ss << "        }\n";
                ss << "    }\n";
                break;
            }

            case OpType::MatMul: {
                Node* a = node->inputs()[0];
                Node* b = node->inputs()[1];
                size_t rank_a = a->shape().ndim();
                size_t rank_b = b->shape().ndim();
                int64_t M = a->shape()[rank_a - 2];
                int64_t K = a->shape()[rank_a - 1];
                int64_t N = b->shape()[rank_b - 1];
                int64_t matrix_size = M * N;
                int64_t batch_count = (matrix_size > 0) ? (numel / matrix_size) : 1;

                ss << "    std::memset(node_" << node->id() << ", 0, " << numel << " * sizeof(" << type_str << "));\n";
                if (batch_count > 1) {
                    ss << "    for (int64_t b_idx = 0; b_idx < " << batch_count << "; ++b_idx) {\n";
                    ss << "        const " << type_str << "* a_ptr = node_" << a->id() << " + b_idx * (" << (M * K) << ");\n";
                    ss << "        const " << type_str << "* b_ptr = node_" << b->id() << " + b_idx * (" << (K * N) << ");\n";
                    ss << "        " << type_str << "* c_ptr = node_" << node->id() << " + b_idx * (" << (M * N) << ");\n";
                } else {
                    ss << "    {\n";
                    ss << "        const " << type_str << "* a_ptr = node_" << a->id() << ";\n";
                    ss << "        const " << type_str << "* b_ptr = node_" << b->id() << ";\n";
                    ss << "        " << type_str << "* c_ptr = node_" << node->id() << ";\n";
                }

                bool use_fma = (options_.target_isa == TargetISA::AVX2_FMA || (options_.target_isa == TargetISA::AVX2 && options_.enable_fma));

                if (is_avx && node->dtype() == DType::Float32) {
                    // Cache-blocked loop tiling with AVX2 (and optional FMA) vectorization
                    ss << "        constexpr int64_t BM = 32;\n";
                    ss << "        constexpr int64_t BK = 32;\n";
                    ss << "        constexpr int64_t BN = 32;\n";
                    ss << "        for (int64_t i0 = 0; i0 < " << M << "; i0 += BM) {\n";
                    ss << "            int64_t i_max = (i0 + BM < " << M << ") ? i0 + BM : " << M << ";\n";
                    ss << "            for (int64_t k0 = 0; k0 < " << K << "; k0 += BK) {\n";
                    ss << "                int64_t k_max = (k0 + BK < " << K << ") ? k0 + BK : " << K << ";\n";
                    ss << "                for (int64_t j0 = 0; j0 < " << N << "; j0 += BN) {\n";
                    ss << "                    int64_t j_max = (j0 + BN < " << N << ") ? j0 + BN : " << N << ";\n";
                    ss << "                    for (int64_t i = i0; i < i_max; ++i) {\n";
                    ss << "                        for (int64_t k = k0; k < k_max; ++k) {\n";
                    ss << "                            float a_ik = a_ptr[i * " << K << " + k];\n";
                    ss << "                            __m256 va = _mm256_set1_ps(a_ik);\n";
                    ss << "                            int64_t j = j0;\n";
                    ss << "                            for (; j <= j_max - 8; j += 8) {\n";
                    ss << "                                __m256 vb = _mm256_loadu_ps(b_ptr + k * " << N << " + j);\n";
                    ss << "                                __m256 vc = _mm256_loadu_ps(c_ptr + i * " << N << " + j);\n";
                    if (use_fma) {
                        ss << "                                vc = _mm256_fmadd_ps(va, vb, vc);\n";
                    } else {
                        ss << "                                vc = _mm256_add_ps(_mm256_mul_ps(va, vb), vc);\n";
                    }
                    ss << "                                _mm256_storeu_ps(c_ptr + i * " << N << " + j, vc);\n";
                    ss << "                            }\n";
                    ss << "                            for (; j < j_max; ++j) {\n";
                    ss << "                                c_ptr[i * " << N << " + j] += a_ik * b_ptr[k * " << N << " + j];\n";
                    ss << "                            }\n";
                    ss << "                        }\n";
                    ss << "                    }\n";
                    ss << "                }\n";
                    ss << "            }\n";
                    ss << "        }\n";
                } else {
                    // Portable scalar fallback
                    ss << "        for (int64_t i = 0; i < " << M << "; ++i) {\n";
                    ss << "            for (int64_t k = 0; k < " << K << "; ++k) {\n";
                    ss << "                " << type_str << " a_ik = a_ptr[i * " << K << " + k];\n";
                    ss << "                for (int64_t j = 0; j < " << N << "; ++j) {\n";
                    ss << "                    c_ptr[i * " << N << " + j] += a_ik * b_ptr[k * " << N << " + j];\n";
                    ss << "                }\n";
                    ss << "            }\n";
                    ss << "        }\n";
                }
                ss << "    }\n";
                break;
            }

            case OpType::FusedElementwise: {
                // Generates fused expression e.g. relu(add(a, b))
                Node* a = node->inputs()[0];
                Node* b = node->inputs().size() > 1 ? node->inputs()[1] : nullptr;
                if (is_avx && node->dtype() == DType::Float32 && numel >= 8 &&
                    (!b || (a->shape() == b->shape() && a->shape().ndim() > 0 && a->shape().numel() > 1))) {
                    ss << "    {\n";
                    ss << "        int64_t i = 0;\n";
                    ss << "        int64_t limit = " << numel << " - 7;\n";
                    ss << "        __m256 zero = _mm256_setzero_ps();\n";
                    ss << "        for (; i < limit; i += 8) {\n";
                    ss << "            __m256 va = _mm256_loadu_ps(node_" << a->id() << " + i);\n";
                    if (b) {
                        ss << "            __m256 vb = _mm256_loadu_ps(node_" << b->id() << " + i);\n";
                        ss << "            __m256 vr = _mm256_max_ps(_mm256_add_ps(va, vb), zero);\n";
                    } else {
                        ss << "            __m256 vr = _mm256_max_ps(va, zero);\n";
                    }
                    ss << "            _mm256_storeu_ps(node_" << node->id() << " + i, vr);\n";
                    ss << "        }\n";
                    ss << "        for (; i < " << numel << "; ++i) {\n";
                    if (b) {
                        ss << "            " << type_str << " v = node_" << a->id() << "[i] + node_" << b->id() << "[i];\n";
                    } else {
                        ss << "            " << type_str << " v = node_" << a->id() << "[i];\n";
                    }
                    ss << "            node_" << node->id() << "[i] = (v > 0.0f) ? v : 0.0f;\n";
                    ss << "        }\n";
                    ss << "    }\n";
                } else {
                    ss << "    for (int64_t i = 0; i < " << numel << "; ++i) {\n";
                    std::string idx_a = (a->shape().numel() == 1) ? "0" : "i";
                    if (b) {
                        std::string idx_b = (b->shape().numel() == 1) ? "0" : "i";
                        ss << "        " << type_str << " v = node_" << a->id() << "[" << idx_a << "] + node_" << b->id() << "[" << idx_b << "];\n";
                    } else {
                        ss << "        " << type_str << " v = node_" << a->id() << "[" << idx_a << "];\n";
                    }
                    ss << "        node_" << node->id() << "[i] = (v > 0) ? v : 0;\n";
                    ss << "    }\n";
                }
                break;
            }

            case OpType::ReduceSum:
            case OpType::ReduceMean: {
                Node* a = node->inputs()[0];
                int64_t in_rank = static_cast<int64_t>(a->shape().ndim());
                int64_t in_numel = a->shape().numel();
                int64_t out_numel = node->shape().numel();

                ss << "    std::memset(node_" << node->id() << ", 0, " << out_numel << " * sizeof(" << type_str << "));\n";

                if (in_rank == 0 || in_numel == 0) {
                    if (in_numel > 0 && out_numel > 0) {
                        ss << "    node_" << node->id() << "[0] = node_" << a->id() << "[0];\n";
                    }
                } else if (out_numel == 1) {
                    // Full reduction over all elements
                    ss << "    for (int64_t i = 0; i < " << in_numel << "; ++i) {\n";
                    ss << "        node_" << node->id() << "[0] += node_" << a->id() << "[i];\n";
                    ss << "    }\n";
                    if (node->op_type() == OpType::ReduceMean && in_numel > 0) {
                        ss << "    node_" << node->id() << "[0] /= " << in_numel << ";\n";
                    }
                } else {
                    // Multidimensional partial reduction
                    const auto& axes = node->axes();
                    std::set<int64_t> norm_axes;
                    if (axes.empty()) {
                        for (int64_t d = 0; d < in_rank; ++d) norm_axes.insert(d);
                    } else {
                        for (int64_t ax : axes) {
                            if (ax < 0) ax += in_rank;
                            norm_axes.insert(ax);
                        }
                    }

                    Strides in_strides = Strides::compute_contiguous(a->shape());
                    Strides out_strides = Strides::compute_contiguous(node->shape());

                    std::vector<int64_t> out_mults(static_cast<size_t>(in_rank), 0);
                    int64_t out_dim_idx = 0;
                    for (int64_t d = 0; d < in_rank; ++d) {
                        if (norm_axes.count(d)) {
                            if (node->keepdims()) {
                                out_dim_idx++;
                            }
                        } else {
                            out_mults[static_cast<size_t>(d)] = out_strides[static_cast<size_t>(out_dim_idx++)];
                        }
                    }

                    for (int64_t d = 0; d < in_rank; ++d) {
                        ss << std::string(static_cast<size_t>(4 + d * 4), ' ')
                           << "for (int64_t i" << d << " = 0; i" << d << " < "
                           << a->shape()[static_cast<size_t>(d)] << "; ++i" << d << ") {\n";
                    }

                    std::string indent(static_cast<size_t>(4 + in_rank * 4), ' ');
                    ss << indent << "int64_t in_idx = ";
                    for (int64_t d = 0; d < in_rank; ++d) {
                        if (d > 0) ss << " + ";
                        ss << "i" << d << " * " << in_strides[static_cast<size_t>(d)];
                    }
                    ss << ";\n";

                    ss << indent << "int64_t out_idx = ";
                    bool first_out = true;
                    for (int64_t d = 0; d < in_rank; ++d) {
                        if (out_mults[static_cast<size_t>(d)] > 0) {
                            if (!first_out) ss << " + ";
                            ss << "i" << d << " * " << out_mults[static_cast<size_t>(d)];
                            first_out = false;
                        }
                    }
                    if (first_out) ss << "0";
                    ss << ";\n";

                    ss << indent << "node_" << node->id() << "[out_idx] += node_" << a->id() << "[in_idx];\n";

                    for (int64_t d = in_rank - 1; d >= 0; --d) {
                        ss << std::string(static_cast<size_t>(4 + d * 4), ' ') << "}\n";
                    }

                    if (node->op_type() == OpType::ReduceMean && in_numel > 0 && out_numel > 0) {
                        int64_t count = in_numel / out_numel;
                        ss << "    for (int64_t o = 0; o < " << out_numel << "; ++o) {\n";
                        ss << "        node_" << node->id() << "[o] /= " << count << ";\n";
                        ss << "    }\n";
                    }
                }
                break;
            }

            case OpType::Transpose: {
                Node* a = node->inputs()[0];
                int64_t in_rank = static_cast<int64_t>(a->shape().ndim());
                if (in_rank <= 1) {
                    ss << "    std::memcpy(node_" << node->id() << ", node_" << a->id()
                       << ", " << numel << " * sizeof(" << type_str << "));\n";
                } else {
                    int64_t dim0 = node->dim0();
                    int64_t dim1 = node->dim1();
                    if (dim0 < 0) dim0 += in_rank;
                    if (dim1 < 0) dim1 += in_rank;

                    Strides in_strides = Strides::compute_contiguous(a->shape());
                    Strides out_strides = Strides::compute_contiguous(node->shape());

                    for (int64_t d = 0; d < in_rank; ++d) {
                        ss << std::string(static_cast<size_t>(4 + d * 4), ' ')
                           << "for (int64_t i" << d << " = 0; i" << d << " < "
                           << a->shape()[static_cast<size_t>(d)] << "; ++i" << d << ") {\n";
                    }

                    std::string indent(static_cast<size_t>(4 + in_rank * 4), ' ');
                    ss << indent << "int64_t in_idx = ";
                    for (int64_t d = 0; d < in_rank; ++d) {
                        if (d > 0) ss << " + ";
                        ss << "i" << d << " * " << in_strides[static_cast<size_t>(d)];
                    }
                    ss << ";\n";

                    ss << indent << "int64_t out_idx = ";
                    for (int64_t d = 0; d < in_rank; ++d) {
                        if (d > 0) ss << " + ";
                        int64_t src_d = d;
                        if (d == dim0) src_d = dim1;
                        else if (d == dim1) src_d = dim0;
                        ss << "i" << src_d << " * " << out_strides[static_cast<size_t>(d)];
                    }
                    ss << ";\n";

                    ss << indent << "node_" << node->id() << "[out_idx] = node_" << a->id() << "[in_idx];\n";

                    for (int64_t d = in_rank - 1; d >= 0; --d) {
                        ss << std::string(static_cast<size_t>(4 + d * 4), ' ') << "}\n";
                    }
                }
                break;
            }

            default:
                break;
        }
    }

    // Free intermediate heap buffers
    for (Node* node : topo) {
        if (!node->is_input() && !output_index.count(node)) {
            ss << "    delete[] node_" << node->id() << ";\n";
        }
    }

    ss << "    return 0;\n";
    ss << "}\n\n";
    ss << "} // extern \"C\"\n";

    return ss.str();
}

std::unique_ptr<Executable> CppBackend::compile(const Graph& graph, KernelCache* cache) {
    IRVerifier::verify(graph);

    std::string canonical_ir = IRPrinter::to_string(graph);
    std::string isa_desc;
    if (options_.target_isa == TargetISA::AVX2_FMA || (options_.target_isa == TargetISA::AVX2 && options_.enable_fma)) {
        isa_desc = " avx2_fma";
    } else if (options_.target_isa == TargetISA::AVX2) {
        isa_desc = " avx2_nofma";
    } else {
        isa_desc = " scalar";
    }
    std::string compiler_info = options_.compiler_path + " " + options_.opt_level + isa_desc + " gcc-13.3.0";

    std::string key = KernelCache::compute_key(canonical_ir, "tinytensor_v0.1.1", compiler_info);
    std::string so_path;

    // Check cache
    if (cache && cache->get(key, so_path)) {
        void* handle = dlopen(so_path.c_str(), RTLD_NOW);
        if (handle) {
            auto fn = reinterpret_cast<KernelEntryFn>(dlsym(handle, "tinytensor_kernel_entry"));
            if (fn) {
                std::vector<Shape> in_shapes;
                std::vector<DType> in_dtypes;
                for (Node* in : graph.inputs()) {
                    in_shapes.push_back(in->shape());
                    in_dtypes.push_back(in->dtype());
                }
                std::vector<Shape> out_shapes;
                std::vector<DType> out_dtypes;
                for (Node* out : graph.outputs()) {
                    out_shapes.push_back(out->shape());
                    out_dtypes.push_back(out->dtype());
                }
                std::string cached_source;
                cache->get_source(key, cached_source);
                return std::make_unique<Executable>(handle, fn, in_shapes, in_dtypes,
                                                    out_shapes, out_dtypes,
                                                    std::vector<size_t>{}, so_path, cached_source);
            }
            dlclose(handle);
        }
        // Invalidate and remove corrupted cache entry so it can heal
        std::error_code ec;
        std::filesystem::remove(so_path, ec);
    }

    // Cross-process compilation coordination: acquire key compile lock if cache enabled
    std::unique_ptr<FileLockGuard> compile_lock;
    if (cache) {
        compile_lock = std::make_unique<FileLockGuard>(cache->acquire_compile_lock(key));
        // Re-check cache after acquiring compile lock; another process may have completed compilation
        if (cache->get(key, so_path, false)) {
            void* handle = dlopen(so_path.c_str(), RTLD_NOW);
            if (handle) {
                auto fn = reinterpret_cast<KernelEntryFn>(dlsym(handle, "tinytensor_kernel_entry"));
                if (fn) {
                    std::vector<Shape> in_shapes;
                    std::vector<DType> in_dtypes;
                    for (Node* in : graph.inputs()) {
                        in_shapes.push_back(in->shape());
                        in_dtypes.push_back(in->dtype());
                    }
                    std::vector<Shape> out_shapes;
                    std::vector<DType> out_dtypes;
                    for (Node* out : graph.outputs()) {
                        out_shapes.push_back(out->shape());
                        out_dtypes.push_back(out->dtype());
                    }
                    std::string cached_source;
                    cache->get_source(key, cached_source);
                    return std::make_unique<Executable>(handle, fn, in_shapes, in_dtypes,
                                                        out_shapes, out_dtypes,
                                                        std::vector<size_t>{}, so_path, cached_source);
                }
                dlclose(handle);
            }
            std::error_code ec;
            std::filesystem::remove(so_path, ec);
        }
    }

    // Verify compiler binary existence before creating temporary directories or forking
    if (!std::filesystem::exists(options_.compiler_path) || std::filesystem::is_directory(options_.compiler_path)) {
        throw CompileError("Compiler binary not found or is a directory at: " + options_.compiler_path);
    }

    auto start_time = std::chrono::high_resolution_clock::now();

    // Generate code
    std::string code = generate_code(graph);

    // Controlled temp files
    char temp_dir_template[] = "/tmp/tinytensor_XXXXXX";
    char* temp_dir = mkdtemp(temp_dir_template);
    if (!temp_dir) {
        throw CompileError("Failed to create temporary directory for compilation");
    }

    std::string cpp_path = std::string(temp_dir) + "/kernel.cpp";
    std::string temp_so_path = std::string(temp_dir) + "/kernel.so";

    std::ofstream out(cpp_path);
    if (!out.is_open()) {
        throw CompileError("Failed to write generated C++ code to " + cpp_path);
    }
    out << code;
    out.close();

    // Prepare arguments for compilation: pass arguments safely without shell interpolation
    std::vector<std::string> args = {
        options_.compiler_path,
        options_.opt_level,
        "-fPIC",
        "-shared",
        "-std=c++20"
    };

    if (options_.target_isa == TargetISA::AVX2_FMA || (options_.target_isa == TargetISA::AVX2 && options_.enable_fma)) {
        args.push_back("-mavx2");
        args.push_back("-mfma");
    } else if (options_.target_isa == TargetISA::AVX2) {
        args.push_back("-mavx2");
        args.push_back("-mno-fma");
    }

    args.push_back(cpp_path);
    args.push_back("-o");
    args.push_back(temp_so_path);

    std::vector<char*> argv;
    for (auto& s : args) {
        argv.push_back(s.data());
    }
    argv.push_back(nullptr);

    // Create pipes for stdout/stderr capture
    int pipefd[2];
    if (pipe(pipefd) != 0) {
        throw CompileError("Failed to create pipe for compiler output");
    }

    pid_t pid = fork();
    if (pid == -1) {
        close(pipefd[0]);
        close(pipefd[1]);
        throw CompileError("Failed to fork compiler process");
    }

    if (pid == 0) {
        // Child process
        close(pipefd[0]);
        dup2(pipefd[1], STDOUT_FILENO);
        dup2(pipefd[1], STDERR_FILENO);
        close(pipefd[1]);

        execv(options_.compiler_path.c_str(), argv.data());
        _exit(127);
    }

    // Parent process
    close(pipefd[1]);

    // Set non-blocking on pipe to prevent deadlock on read while process is running
    fcntl(pipefd[0], F_SETFL, O_NONBLOCK);

    std::string compiler_output;
    char buf[1024];

    int status = 0;
    bool timed_out = false;
    int timeout_ms = options_.timeout_seconds * 1000;
    int elapsed_ms = 0;
    const int poll_interval_ms = 10;

    while (true) {
        // Drain all currently available pipe data in non-blocking mode to prevent pipe buffer deadlock
        while (true) {
            ssize_t bytes_read = read(pipefd[0], buf, sizeof(buf) - 1);
            if (bytes_read > 0) {
                buf[bytes_read] = '\0';
                compiler_output += buf;
            } else {
                break;
            }
        }

        pid_t ret = waitpid(pid, &status, WNOHANG);
        if (ret == pid) {
            // Process terminated naturally
            break;
        } else if (ret == -1) {
            close(pipefd[0]);
            throw CompileError("waitpid failed on compiler process");
        }

        if (elapsed_ms >= timeout_ms) {
            timed_out = true;
            kill(pid, SIGKILL);
            waitpid(pid, &status, 0); // Reclaim child zombie
            break;
        }

        std::this_thread::sleep_for(std::chrono::milliseconds(poll_interval_ms));
        elapsed_ms += poll_interval_ms;
    }

    // Drain remaining output from pipe
    while (true) {
        ssize_t bytes_read = read(pipefd[0], buf, sizeof(buf) - 1);
        if (bytes_read <= 0) break;
        buf[bytes_read] = '\0';
        compiler_output += buf;
    }
    close(pipefd[0]);

    if (timed_out) {
        throw CompileError("Kernel compilation timed out after " +
                           std::to_string(options_.timeout_seconds) + " seconds");
    }

    auto end_time = std::chrono::high_resolution_clock::now();
    double compile_ms = std::chrono::duration<double, std::milli>(end_time - start_time).count();
    if (cache) {
        cache->add_compile_time(compile_ms);
    }

    if (!WIFEXITED(status) || WEXITSTATUS(status) != 0) {
        throw CompileError("Kernel compilation failed with code " +
                           std::to_string(WEXITSTATUS(status)) + ":\n" + compiler_output);
    }

    if (!std::filesystem::exists(temp_so_path)) {
        throw CompileError("Compiled shared library not found at " + temp_so_path);
    }

    // Commit to cache if enabled
    std::string final_so = temp_so_path;
    if (cache) {
        cache->put(key, temp_so_path, code);
        final_so = cache->cache_dir() + "/" + key + ".so";
    }

    // Load compiled library
    void* handle = dlopen(final_so.c_str(), RTLD_NOW);
    if (!handle && std::filesystem::exists(temp_so_path)) {
        handle = dlopen(temp_so_path.c_str(), RTLD_NOW);
        final_so = temp_so_path;
    }
    if (!handle) {
        throw CompileError("Failed to dlopen compiled kernel: " + std::string(dlerror()));
    }

    auto fn = reinterpret_cast<KernelEntryFn>(dlsym(handle, "tinytensor_kernel_entry"));
    if (!fn) {
        dlclose(handle);
        throw CompileError("Failed to locate tinytensor_kernel_entry in compiled library");
    }

    std::vector<Shape> in_shapes;
    std::vector<DType> in_dtypes;
    for (Node* in : graph.inputs()) {
        in_shapes.push_back(in->shape());
        in_dtypes.push_back(in->dtype());
    }
    std::vector<Shape> out_shapes;
    std::vector<DType> out_dtypes;
    for (Node* out_node : graph.outputs()) {
        out_shapes.push_back(out_node->shape());
        out_dtypes.push_back(out_node->dtype());
    }

    return std::make_unique<Executable>(handle, fn, in_shapes, in_dtypes,
                                        out_shapes, out_dtypes,
                                        std::vector<size_t>{}, final_so, code);
}

